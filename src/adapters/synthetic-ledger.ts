import {
  commandSchema,
  snapshotSchema,
  type Ledger,
  type LedgerCommand,
  type Snapshot,
} from "../application/contracts";

export class SyntheticLedger implements Ledger {
  private snapshot: Snapshot = {
    schemaVersion: 6,
    epoch: crypto.randomUUID(),
    revision: 0,
    accounts: [],
    expenses: [],
    housePayments: [],
    imports: [],
    bankEvents: [],
    reversals: [],
    auditCount: 0,
  };
  private completed = new Map<string, string>();

  async read() {
    const snapshot = structuredClone(this.snapshot);
    const referencedEventIds = new Set(
      snapshot.imports.flatMap((record) =>
        record.rows.map((row) => row.eventId),
      ),
    );
    snapshot.bankEvents = snapshot.bankEvents.filter((event) =>
      referencedEventIds.has(event.id),
    );
    return snapshot;
  }

  async resolve(command: LedgerCommand) {
    const parsed = commandSchema.parse(command);
    const previous = this.completed.get(parsed.commandId);
    if (!previous) return null;
    if (previous !== JSON.stringify(parsed))
      throw new Error("Command identity conflict.");
    return this.read();
  }

  async execute(input: LedgerCommand) {
    const command = commandSchema.parse(input);
    const previous = this.completed.get(command.commandId);
    if (previous) {
      if (previous !== JSON.stringify(command))
        throw new Error("Command identity conflict.");
      return this.read();
    }
    if (
      command.expectedEpoch !== this.snapshot.epoch ||
      command.expectedRevision !== this.snapshot.revision
    )
      throw new Error("The ledger changed. Reload before saving.");
    const next = structuredClone(this.snapshot);
    if (command.operation.type === "commitImport") {
      const record = command.operation.import;
      if (!next.accounts.some((account) => account.id === record.accountId))
        throw new Error("Account not found.");
      if (record.reconciliations.length)
        throw new Error(
          "Import reconciliation history is generated by audited commands.",
        );
      const exact = next.imports.find(
        (previous) =>
          previous.accountId === record.accountId &&
          previous.profile === record.profile &&
          previous.contentHash === record.contentHash,
      );
      if (!exact) {
        for (const row of record.rows) {
          for (const rejectedEventId of row.rejectedEventIds) {
            const rejected = next.bankEvents.find(
              (event) => event.id === rejectedEventId,
            );
            if (
              !rejected ||
              rejected.accountId !== record.accountId ||
              rejected.date !== row.observation.date ||
              rejected.amountCents !== row.observation.amountCents ||
              rejected.comparisonDescription !==
                row.observation.comparisonDescription
            )
              throw new Error("Rejected overlap is no longer compatible.");
          }
          const event = next.bankEvents.find(
            (event) => event.id === row.eventId,
          );
          if (row.decision === "existing") {
            if (
              !event ||
              event.accountId !== record.accountId ||
              event.date !== row.observation.date ||
              event.amountCents !== row.observation.amountCents ||
              event.comparisonDescription !==
                row.observation.comparisonDescription
            )
              throw new Error("Selected match is no longer compatible.");
          } else {
            if (event) throw new Error("Event identity already exists.");
            const {
              date,
              description,
              comparisonDescription,
              amountCents,
              balanceCents,
              currency,
            } = row.observation;
            next.bankEvents.push({
              id: row.eventId,
              accountId: record.accountId,
              date,
              description,
              comparisonDescription,
              amountCents,
              balanceCents,
              currency,
            });
          }
        }
        next.imports.push(record);
      }
    } else if (command.operation.type === "reconcileImport") {
      const operation = command.operation;
      const record = next.imports.find(
        (item) => item.id === operation.importId,
      );
      const row = record?.rows.find(
        (item) => item.observation.ordinal === operation.ordinal,
      );
      const candidate = next.bankEvents.find(
        (event) => event.id === operation.candidateEventId,
      );
      if (
        !record ||
        !row ||
        row.decision !== "new" ||
        row.eventId !== operation.expectedEventId ||
        !row.rejectedEventIds.includes(operation.candidateEventId) ||
        !candidate ||
        candidate.accountId !== record.accountId ||
        candidate.date !== row.observation.date ||
        candidate.amountCents !== row.observation.amountCents ||
        candidate.comparisonDescription !==
          row.observation.comparisonDescription ||
        record.rows.some(
          (other) =>
            other !== row && other.eventId === operation.candidateEventId,
        )
      )
        throw new Error("The rejected match is no longer available.");
      record.reconciliations.push({
        ordinal: row.observation.ordinal,
        priorEventId: row.eventId,
        selectedEventId: candidate.id,
        reason: operation.reason,
        commandId: command.commandId,
      });
      row.eventId = candidate.id;
      row.decision = "existing";
      row.rejectedEventIds = row.rejectedEventIds.filter(
        (id) => id !== candidate.id,
      );
    } else if (command.operation.type === "createAccount") {
      const newAccount = command.operation.account;
      if (next.accounts.some((account) => account.id === newAccount.id))
        throw new Error("Account already exists.");
      next.accounts.push(newAccount);
    } else if (command.operation.type === "reverseExpense") {
      const { expenseId, reason } = command.operation;
      if (!next.expenses.some((expense) => expense.id === expenseId))
        throw new Error("Expense not found.");
      if (next.reversals.some((reversal) => reversal.expenseId === expenseId))
        throw new Error("Expense is already reversed.");
      if (
        next.housePayments.some((payment) =>
          payment.applications.some(
            (application) => application.expenseId === expenseId,
          ),
        )
      )
        throw new Error(
          "Reverse linked House payments before reversing this expense.",
        );
      next.reversals.push({ expenseId, reason });
    } else if (command.operation.type === "applyHousePayment") {
      const payment = command.operation.payment;
      const account = next.accounts.find(
        (candidate) => candidate.id === payment.accountId,
      );
      if (!account || account.role !== "common" || account.kind !== "asset")
        throw new Error("House payments require a common asset account.");
      if (next.housePayments.some((existing) => existing.id === payment.id))
        throw new Error("House payment already exists.");
      for (const application of payment.applications) {
        const expense = next.expenses.find(
          (candidate) => candidate.id === application.expenseId,
        );
        if (
          !expense ||
          next.reversals.some((reversal) => reversal.expenseId === expense.id)
        )
          throw new Error("House claim is no longer active.");
        const claimCents = expense.allocations
          .filter((line) => line.bucket === "house")
          .reduce((total, line) => {
            if (!line.fundingSources.length) {
              const funding = next.accounts.find(
                (candidate) => candidate.id === expense.accountId,
              );
              return funding?.role === "personal"
                ? total + BigInt(line.amountCents)
                : total;
            }
            return (
              total +
              line.fundingSources
                .filter((source) => {
                  if (source.kind !== "account" || !source.accountId)
                    return false;
                  return next.accounts.some(
                    (candidate) =>
                      candidate.id === source.accountId &&
                      candidate.role === "personal",
                  );
                })
                .reduce((sum, source) => sum + BigInt(source.amountCents), 0n)
            );
          }, 0n);
        const appliedCents = next.housePayments
          .flatMap((existing) => existing.applications)
          .filter((existing) => existing.expenseId === expense.id)
          .reduce(
            (total, existing) => total + BigInt(existing.amountCents),
            0n,
          );
        if (BigInt(application.amountCents) > claimCents - appliedCents)
          throw new Error("House payment exceeds the outstanding claim.");
      }
      next.housePayments.push(payment);
    } else {
      const operation = command.operation;
      if (operation.type === "correctExpense") {
        if (
          !next.expenses.some((expense) => expense.id === operation.expenseId)
        )
          throw new Error("Expense not found.");
        if (
          next.reversals.some(
            (reversal) => reversal.expenseId === operation.expenseId,
          )
        )
          throw new Error("Expense is already reversed.");
        if (
          next.housePayments.some((payment) =>
            payment.applications.some(
              (application) => application.expenseId === operation.expenseId,
            ),
          )
        )
          throw new Error(
            "Reverse linked House payments before correcting this expense.",
          );
        next.reversals.push({
          expenseId: operation.expenseId,
          reason: operation.reason,
        });
      }
      const expense =
        operation.type === "correctExpense"
          ? operation.replacement
          : operation.expense;
      if (!next.accounts.some((account) => account.id === expense.accountId))
        throw new Error("Account not found.");
      for (const source of expense.allocations.flatMap(
        (line) => line.fundingSources,
      )) {
        if (
          source.kind === "account" &&
          !next.accounts.some((account) => account.id === source.accountId)
        )
          throw new Error("Funding source account not found.");
      }
      if (next.expenses.some((existing) => existing.id === expense.id))
        throw new Error("Expense already exists.");
      const allocationIds = new Set(
        next.expenses.flatMap((existing) =>
          existing.allocations.map((line) => line.id),
        ),
      );
      if (expense.allocations.some((line) => allocationIds.has(line.id)))
        throw new Error("Allocation already exists.");
      next.expenses.push(expense);
    }
    next.revision += 1;
    next.auditCount += 1;
    this.snapshot = snapshotSchema.parse(next);
    this.completed.set(command.commandId, JSON.stringify(command));
    return this.read();
  }
}
